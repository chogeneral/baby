-- ---------------------------------------------------------------------------
-- 1) posts: 뼈대가 없을 때만 전체 생성
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.posts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL DEFAULT '',
  content text,
  author_email text,
  -- 앱 read/insert: row.nickname — 반드시 이 이름(작성자 닉네임)
  nickname text,
  child_birth_year integer NOT NULL DEFAULT 0,
  -- boardKind 는 DB 에서 category 문자열로 저장 (아기이야기, 꼬꼬마)
  category text,
  prefix text,
  view_count integer NOT NULL DEFAULT 0,
  edit_password text,
  created_at timestamptz NOT NULL DEFAULT now()
);


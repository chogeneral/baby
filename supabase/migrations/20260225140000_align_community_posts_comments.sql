-- ---------------------------------------------------------------------------
-- 2) comments: posts.id (bigint) 와 연결
--    기존 테이블이 post_id 타입이 다르면(예: text) 수동 점검 필요
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.comments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id bigint NOT NULL,
  content text NOT NULL,
  author_email text,
  -- 앱 insert 필드명 — post 의 nickname 과 구분(댓글만 author_nickname)
  author_nickname text,
  parent_id bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT comments_post_fk
    FOREIGN KEY (post_id) REFERENCES public.posts (id) ON DELETE CASCADE,
  CONSTRAINT comments_parent_fk
    FOREIGN KEY (parent_id) REFERENCES public.comments (id) ON DELETE CASCADE
);

-- 테이블은 있었는데 제약/컬럼만 덜 쓴 경우(제약이 이미 있으면 이 블록은 실패할 수 있어 주석 권장)
-- 실패 시: 대시보드에서 FK / 컬럼을 맞춘 뒤 다시 시도
ALTER TABLE public.comments ADD COLUMN IF NOT EXISTS post_id bigint;
ALTER TABLE public.comments ADD COLUMN IF NOT EXISTS content text;

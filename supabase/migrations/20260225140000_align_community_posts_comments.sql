-- posts 가 먼저 있었고 comments 만 예전에 만들어진 경우, FK 를 수동으로 붙인다(데이터·타입이 맞을 때만 성공)
DO $fk$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'comments_post_fk' AND conrelid = 'public.comments'::regclass) THEN
    ALTER TABLE public.comments
      ADD CONSTRAINT comments_post_fk
      FOREIGN KEY (post_id) REFERENCES public.posts (id) ON DELETE CASCADE;
  END IF;
EXCEPTION WHEN OTHERS THEN
  RAISE NOTICE 'comments_post_fk 생략(또는 이미 있음/데이터 불일치): %', SQLERRM;
END;
$fk$;

DO $fkt$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'comments_parent_fk' AND conrelid = 'public.comments'::regclass) THEN
    ALTER TABLE public.comments
      ADD CONSTRAINT comments_parent_fk
      FOREIGN KEY (parent_id) REFERENCES public.comments (id) ON DELETE CASCADE;
  END IF;
EXCEPTION WHEN OTHERS THEN
  RAISE NOTICE 'comments_parent_fk 생략(또는 이미 있음/데이터 불일치): %', SQLERRM;
END;
$fkt$;

